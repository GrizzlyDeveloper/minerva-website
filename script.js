function setLanguage(language) {
  const useEnglish = language === "en";
  localizedElements.forEach((element) => {
    const key = element.dataset.i18n;
    element.innerHTML = useEnglish
      ? (english[key] ?? russian[key])
      : russian[key];
  });

  document.documentElement.lang = language;
  const labels = [
    [
      ".release-tabs",
      "aria-label",
      "Возможности версии 0.4.22",
      "Features in 0.4.22",
    ],
    [".brand[aria-label]", "aria-label", "Главная Minerva", "Minerva home"],
    ["footer nav", "aria-label", "Навигация в подвале", "Footer navigation"],
    [".auth-flow", "aria-label", "Процесс авторизации", "Sign-in flow"],
    [".signal-row", "aria-label", "Принципы продукта", "Product principles"],
    [
      ".app-window img",
      "alt",
      "Экран инстансов в приложении Minerva",
      "Instance screen in Minerva",
    ],
  ];
  labels.forEach(([selector, attribute, ru, en]) => {
    document
      .querySelector(selector)
      ?.setAttribute(attribute, useEnglish ? en : ru);
  });
  document
    .querySelector(".nav-toggle")
    ?.setAttribute(
      "aria-label",
      useEnglish ? "Toggle navigation" : "Открыть навигацию",
    );
  document
    .querySelector(".nav-toggle")
    ?.setAttribute("title", useEnglish ? "Menu" : "Меню");
  document
    .querySelector(".header-nav")
    ?.setAttribute(
      "aria-label",
      useEnglish ? "Main navigation" : "Основная навигация",
    );
  document
    .querySelector(".language-switch")
    ?.setAttribute("aria-label", useEnglish ? "Language" : "Выбор языка");
  document.querySelectorAll("[data-language]").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.language === language);
    button.setAttribute(
      "aria-pressed",
      String(button.dataset.language === language),
    );
  });
  document.querySelectorAll(".language-switch").forEach((toggle) => {
    toggle.classList.toggle("is-english", useEnglish);
  });

  const metadata = englishMetadata[document.body.dataset.page];
  document.title = useEnglish && metadata ? metadata[0] : originalTitle;
  const description = document.querySelector('meta[name="description"]');
  if (description)
    description.content =
      useEnglish && metadata ? metadata[1] : originalDescription;

  try {
    localStorage.setItem("minerva-language", language);
  } catch {}
}

document.querySelectorAll("[data-language]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

