const localizedElements = [...document.querySelectorAll("[data-i18n]")];
const russian = Object.fromEntries(
  localizedElements.map((element) => [element.dataset.i18n, element.innerHTML]),
);
const originalTitle = document.title;
const originalDescription =
  document.querySelector('meta[name="description"]')?.content ?? "";
const englishMetadata = {
  home: [
    "Minerva | Minecraft Java Launcher",
    "Minerva is a focused Windows launcher and instance manager for Minecraft: Java Edition.",
  ],
  privacy: ["Privacy | Minerva", "Minerva privacy policy."],
  terms: ["Terms | Minerva", "Minerva terms of use."],
};

function setLanguage(language) {
  const useEnglish = language === "en";
  localizedElements.forEach((element) => {
    const key = element.dataset.i18n;
    element.innerHTML = useEnglish
      ? (english[key] ?? russian[key])
      : russian[key];
  });

  document.documentElement.lang = language;
  document
    .querySelector(".nav-toggle")
    ?.setAttribute(
      "aria-label",
      useEnglish ? "Toggle navigation" : "Открыть навигацию",
    );
  document
    .querySelector(".nav-toggle")
    ?.setAttribute("title", useEnglish ? "Menu" : "Меню");
  document
    .querySelector(".header-nav")
    ?.setAttribute(
      "aria-label",
      useEnglish ? "Main navigation" : "Основная навигация",
    );
  document
    .querySelector(".language-switch")
    ?.setAttribute("aria-label", useEnglish ? "Language" : "Выбор языка");
  document.querySelectorAll("[data-language]").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.language === language);
    button.setAttribute(
      "aria-pressed",
      String(button.dataset.language === language),
    );
  });
  document.querySelectorAll(".language-switch").forEach((toggle) => {
    toggle.classList.toggle("is-english", useEnglish);
  });

  const metadata = englishMetadata[document.body.dataset.page];
  document.title = useEnglish && metadata ? metadata[0] : originalTitle;
  const description = document.querySelector('meta[name="description"]');
  if (description)
    description.content =
      useEnglish && metadata ? metadata[1] : originalDescription;

  try {
    localStorage.setItem("minerva-language", language);
  } catch {}
}

document.querySelectorAll("[data-language]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

let initialLanguage = "ru";
try {
  initialLanguage = localStorage.getItem("minerva-language") || "ru";
} catch {}
setLanguage(initialLanguage === "en" ? "en" : "ru");

const navigationToggle = document.querySelector(".nav-toggle");
const navigation = document.querySelector(".header-nav");

navigationToggle?.addEventListener("click", () => {
  const isOpen = navigationToggle.getAttribute("aria-expanded") === "true";
  navigationToggle.setAttribute("aria-expanded", String(!isOpen));
  navigation?.classList.toggle("is-open", !isOpen);
});

navigation?.addEventListener("click", (event) => {
  if (!(event.target instanceof HTMLAnchorElement)) return;
  navigationToggle?.setAttribute("aria-expanded", "false");
  navigation.classList.remove("is-open");
});

const reducedMotion = window.matchMedia(
  "(prefers-reduced-motion: reduce)",
).matches;
const revealItems = document.querySelectorAll(".reveal");

if (reducedMotion || !("IntersectionObserver" in window)) {
  revealItems.forEach((item) => item.classList.add("is-visible"));
} else {
  const revealObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("is-visible");
        revealObserver.unobserve(entry.target);
      });
    },
    { threshold: 0.12, rootMargin: "0px 0px -8% 0px" },
  );
  revealItems.forEach((item) => revealObserver.observe(item));
}

document.addEventListener("keydown", (event) => {
  if (
    event.key === "Escape" &&
    navigationToggle?.getAttribute("aria-expanded") === "true"
  ) {
    navigationToggle.setAttribute("aria-expanded", "false");
    navigation?.classList.remove("is-open");
    navigationToggle.focus();
  }
});
